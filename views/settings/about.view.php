<script>
  document.addEventListener('DOMContentLoaded', () => {
    const OPEN_MAXH = 'max-h-96';
    const CLOSED_MAXH = 'max-h-0';

    document.querySelectorAll('[data-accordion-toggle]').forEach(button => {
      const panel = button.nextElementSibling;
      const icon = button.querySelector('.material-symbols-outlined');

      if (panel) {
        panel.classList.add(CLOSED_MAXH, 'overflow-hidden', 'opacity-0', 'transition-all', 'duration-300', 'ease-in-out');
      }

      button.setAttribute('aria-expanded', 'false');

      button.addEventListener('click', () => {
        if (!panel) return;
        const isOpen = panel.classList.contains(OPEN_MAXH);

        panel.classList.toggle(CLOSED_MAXH, isOpen);
        panel.classList.toggle(OPEN_MAXH, !isOpen);

        panel.classList.toggle('opacity-0', isOpen);
        panel.classList.toggle('opacity-100', !isOpen);
        panel.classList.toggle('py-4', !isOpen);

        button.classList.toggle('bg-overlay-dark/75', !isOpen);
        button.classList.toggle('text-red-500', !isOpen);
        button.classList.toggle('border-red-500', !isOpen);

        if (icon) icon.classList.toggle('rotate-180', !isOpen);

        button.setAttribute('aria-expanded', String(!isOpen));
      });
    });
  });
</script>
